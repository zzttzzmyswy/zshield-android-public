package top.zztweb.zshield.filters

import android.content.Context
import java.io.File
import java.io.FileOutputStream
import java.io.IOException

/**
 * On-disk home of the filter system, under the app's private `files/filters/` directory.
 *
 * Layout:
 * ```
 * files/filters/state.json        # FilterState (atomic writes only)
 * files/filters/lists/<id>.txt    # downloaded list bodies, replaced atomically
 * files/filters/compiled/         # dns.bin + engine.bin written by the Rust core
 * ```
 *
 * Everything here is deliberately plain files: a list body is something you may want to look at
 * with `adb shell cat`, and the compiled artifacts are read by the native core which knows nothing
 * about Android storage abstractions. Writes go through [writeAtomically] so a crash mid-write can
 * never leave a truncated state file or half a list — the reader either sees the old file or the new
 * one, never a mixture.
 */
class FilterStore(private val rootDir: File) {

    constructor(context: Context) : this(File(context.filesDir, ROOT_DIR_NAME))

    val stateFile: File get() = File(rootDir, STATE_FILE_NAME)
    val listsDir: File get() = File(rootDir, LISTS_DIR_NAME)
    val compiledDir: File get() = File(rootDir, COMPILED_DIR_NAME)

    /** Create the directory tree. Idempotent and safe to call from any thread. */
    fun ensureDirectories() {
        rootDir.mkdirs()
        listsDir.mkdirs()
        compiledDir.mkdirs()
    }

    /** Body file for one list. */
    fun listFile(id: String): File = File(listsDir, "${sanitizeId(id)}.txt")

    /** Scratch file a download is written to before it replaces the previous body. */
    fun listTempFile(id: String): File = File(listsDir, "${sanitizeId(id)}.txt.part")

    fun readState(): FilterState {
        val file = stateFile
        if (!file.isFile) return FilterState()
        return try {
            FilterState.fromJson(file.readText(Charsets.UTF_8))
        } catch (error: Exception) {
            // A corrupt state file must not brick filtering: fall back to defaults, keep the old
            // file around under a `.corrupt` name so it can be inspected, and carry on.
            android.util.Log.w("ZShield", "cannot read filter state, starting fresh", error)
            runCatching { file.renameTo(File(rootDir, "$STATE_FILE_NAME.corrupt")) }
            FilterState()
        }
    }

    fun writeState(state: FilterState) {
        ensureDirectories()
        writeAtomically(stateFile, state.toJson().toByteArray(Charsets.UTF_8))
    }

    /**
     * Replace [target] with [bytes] atomically: write `<name>.part`, fsync, then rename.
     *
     * The `rename` is the commit point. On POSIX a rename within one filesystem is atomic, so a
     * reader either opens the previous file or the new one; a crash before the rename leaves the
     * previous file untouched and only a stray `.part`, which the next write overwrites.
     */
    fun writeAtomically(target: File, bytes: ByteArray) {
        target.parentFile?.mkdirs()
        // Per-attempt temporary name: if a previous attempt died between `create` and `rename`, its
        // `.part` file would otherwise be silently overwritten here — harmless — but two writers
        // sharing one temporary name is not (the loser's rename fails). A unique suffix means the
        // only remaining constraint is the final rename, which is atomic on POSIX.
        val temp = File(target.parentFile, "${target.name}.${System.nanoTime()}.part")
        try {
            FileOutputStream(temp).use { stream ->
                stream.write(bytes)
                stream.flush()
                stream.fd.sync()
            }
            if (!temp.renameTo(target)) {
                throw IOException("cannot rename ${temp.name} -> ${target.name}")
            }
        } finally {
            if (temp.exists()) temp.delete()
            // Sweep any stale temporary left by a killed process; they are always regenerable.
            target.parentFile?.listFiles { file -> file.name.startsWith("${target.name}.") && file.name.endsWith(".part") }
                ?.forEach { stale -> stale.delete() }
        }
    }

    /** Remove a list's body. */
    fun deleteList(id: String) {
        listFile(id).delete()
        listTempFile(id).delete()
    }

    /** Delete every downloaded body. Used by "clear all data" and by tests. */
    fun deleteAllLists() {
        listsDir.listFiles()?.forEach { it.delete() }
    }

    companion object {
        const val ROOT_DIR_NAME = "filters"
        const val STATE_FILE_NAME = "state.json"
        const val LISTS_DIR_NAME = "lists"
        const val COMPILED_DIR_NAME = "compiled"

        /**
         * Reduce an arbitrary list id to a safe file name.
         *
         * Ids are generated by this app (`adguard-base`, `custom-<sha1 prefix>`), but a catalog
         * entry is data: a future edit could put a `/` or `..` in one, and a path-traversal bug in
         * a file name generator is a classic. Keeping only `[a-z0-9._-]` costs nothing.
         */
        fun sanitizeId(id: String): String {
            val safe = id.lowercase().map { character ->
                if (character in 'a'..'z' || character in '0'..'9' || character == '-' || character == '_' || character == '.') {
                    character
                } else {
                    '_'
                }
            }.joinToString("")
            // Remove every `.` so a `..` can never survive as a path component.
            return safe.replace(".", "").ifEmpty { "list" }
        }
    }
}
